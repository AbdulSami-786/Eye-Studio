/** All unique categories */
export const categories = [...new Set(products.map((p) => p.category))];

/** All unique subcategories */
export const subcategories = [...new Set(products.map((p) => p.subcategory))];

/** All unique materials */
export const materials = [...new Set(products.map((p) => p.material))];

/** Filter by category */
export const getByCategory = (cat) =>
  products.filter((p) => p.category === cat);

/** Filter by subcategory */
export const getBySubcategory = (sub) =>
  products.filter((p) => p.subcategory === sub);

/** Filter by material */
export const getByMaterial = (mat) =>
  products.filter((p) => p.material === mat);

/** Find single product by id */
export const getById = (id) => products.find((p) => p.id === id) ?? null;

/** All products on sale */
export const getSaleProducts = () =>
  products.filter((p) => p.badges.includes("Sale"));

/** All prescription-ready products */
export const getPrescriptionReady = () =>
  products.filter((p) => p.prescription_ready === true);




